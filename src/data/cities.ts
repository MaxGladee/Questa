export const DEFAULT_CITY = CITIES[0]

/** Центр карты для города. Незнакомый город открывается на Екатеринбурге. */
export function cityCenter (name?: string | null): [number, number] {
  return CITIES.find((city) => city.name === name)?.center ?? DEFAULT_CITY.center
}
