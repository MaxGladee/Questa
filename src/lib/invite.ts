/**
 * Ссылки на приложение и тексты приглашений.
 *
 * Приглашают здесь в двух случаях: позвать знакомых на конкретную встречу и
 * позвать их в само приложение. Общего у этих случаев больше, чем разного —
 * адрес, системное окно «поделиться» и запасной путь через буфер обмена, —
 * поэтому всё это живёт в одном месте, а экраны только дают текст.
 */

/**
 * Адрес приложения. Путь начинается со слеша и попадает в хеш: маршруты
 * живут после `#`, иначе на GitHub Pages ссылка ведёт в никуда.
 */
export function appLink (path = ''): string {
  const base = `${window.location.origin}${import.meta.env.BASE_URL}`.replace(/\/+$/, '')
  return path ? `${base}/#${path}` : `${base}/`
}

/** Чем закончилось приглашение — от этого зависит, что сказать человеку. */
export type ShareOutcome = 'shared' | 'copied' | 'cancelled'

/**
 * Отдать приглашение системе. На телефоне открывается обычное окно
 * «поделиться», на компьютере его нет — там текст со ссылкой копируется в
 * буфер. Закрытое окно — не ошибка: человек просто передумал, и молчание
 * здесь лучше подсказки «не получилось».
 */
export async function shareInvite (
  { title, text, url }: { title: string; text: string; url: string },
): Promise<ShareOutcome> {
  if (navigator.share) {
    try {
      await navigator.share({ title, text, url })
      return 'shared'
    } catch (cause) {
      if (cause instanceof Error && cause.name === 'AbortError') return 'cancelled'
      // Прочие промахи (браузер отказался, нет разрешения) — не тупик:
      // ниже приглашение всё равно ляжет в буфер обмена.
    }
  }

  try {
    await navigator.clipboard.writeText(`${text}\n${url}`)
    return 'copied'
  } catch {
    return 'cancelled'
  }
}

/**
 * Приглашение в само приложение — без привязки к встрече.
 *
 * Голая ссылка в мессенджере выглядит как спам, поэтому рядом идёт пара
 * строк о том, что это вообще такое: человек по ту сторону про Questa
 * ничего не знает, и решение открывать её он принимает по этому тексту.
 */
export function appInvite (nickname?: string) {
  const text = [
    nickname ? `${nickname} зовёт вас в Questa.` : 'Зову вас в Questa.',
    '',
    'Это приложение для небольших встреч: собираетесь компанией 2–10 человек,',
    'а встреча превращается в квест — задания, очки и подсказки, куда идти.',
    'Заходите, дальше разберёмся на месте 👇',
  ].join('\n')

  return { title: 'Questa', text, url: appLink() }
}
