--
-- Категорий было шесть: тусовка, чилл, бар, прогулка, настолки и «другое».
-- В «другое» попадало всё остальное — кино, пробежка, выставка, вечер с
-- приставкой, — и от такой категории не было пользы никому: ни подбору
-- заданий (он смотрит на категорию), ни фильтру на карте, ни поиску мест
-- вокруг.
--
-- Категории и интересы лежат в одной таблице interest, и почти все нужные
-- коды там уже есть: спорт, еда, кофе, музыка, кино, искусство, театр,
-- квизы. Не хватало двух.
--
-- Файл можно выполнять повторно.

