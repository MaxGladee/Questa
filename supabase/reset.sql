-- ОЧИСТКА ДАННЫХ. Выполнять осознанно.
--
-- Этот файл стирает всех пользователей и всё, что они создали: профили,
-- встречи, чаты, квесты, оценки, очки и уведомления.
-- Отменить нельзя — резервной копии Supabase на бесплатном тарифе не
-- делает. После выполнения придётся регистрироваться заново, а открытая
-- вкладка приложения будет работать со сломанной сессией, пока её не
-- обновить.
--
-- Чего файл НЕ трогает: саму схему (таблицы, политики доступа, триггеры,
-- функции), справочник интересов и шаблоны квестов, отметки о выполненных
-- миграциях. То есть после очистки база остаётся рабочей и готовой
-- принять новую регистрацию.
--
-- Картинки (аватары, обложки, снимки заданий) этот файл не удаляет:
-- Supabase запрещает трогать таблицы хранилища запросом и отвечает
-- «Direct deletion from storage tables is not allowed». Файлы убираются
-- вручную в разделе Storage → media, и это не срочно: ссылки на них
-- никуда не ведут, они просто занимают место.
--
-- В порядок выполнения миграций этот файл не входит и повторно ничего не
-- ломает: выполнять его можно сколько угодно раз, эффект один и тот же —
-- пустая база.

begin;

-- 1. Что было до очистки — чтобы видеть, что именно удаляется.
select 'до очистки' as когда,
       (select count(*) from auth.users)   as пользователей,
       (select count(*) from event)        as встреч,
       (select count(*) from chat_message) as сообщений;

-- 2. Пользователи. Всё остальное уходит следом по внешним ключам:
--    профиль → его встречи → участники, чат, квест, задания, оценки,
--    очки, уведомления, ачивки, ответы квиза.
delete from auth.users;

-- 3. На случай, если что-то осталось без владельца (например, встреча,
--    созданная до того, как ключи стали каскадными).
delete from event;
delete from notification;
delete from event_reminder;
delete from qp_transaction;
delete from exp_transaction;
delete from streak_log;
delete from complaint;

-- 4. Что осталось: должно быть по нулям везде, кроме справочников.
select 'после очистки' as когда,
       (select count(*) from auth.users)     as пользователей,
       (select count(*) from event)          as встреч,
       (select count(*) from chat_message)   as сообщений,
       (select count(*) from interest)       as интересов_осталось,
       (select count(*) from quest_template) as шаблонов_осталось;

commit;
